const videoList = document.getElementById("videoList");

function renderVideos(data) {
  videoList.innerHTML = "";

  data.forEach(item => {
    const card = document.createElement("div");
    card.className = "card";

    card.innerHTML = `
      <div class="thumb-box">
        <img src="${item.thumbnail}" alt="${item.title}">
        <button class="play">▶</button>
      </div>

      <div class="title">
        <span class="num">${item.number}</span>
        ${item.title}
      </div>
    `;

    card.onclick = () => openModal(item);
    videoList.appendChild(card);
  });
}

function filterVideos(category, element) {
  const filtered = videos.filter(item => item.category === category);

  renderVideos(filtered);

  document.querySelectorAll(".tab").forEach(tab => {
    tab.classList.remove("active");
  });

  element.classList.add("active");
}

function openModal(item) {
  modal.innerHTML = `
    <div class="modal-box" onclick="event.stopPropagation()">
      <button class="close" onclick="closeModal()">×</button>

      <h2>▶ ${item.title} (${item.number})</h2>

      <video
        class="main-video"
        controls
        autoplay
        playsinline
        src="${item.video}">
      </video>

      <div class="sub-title">
        ${item.title} (${item.number}) 다른 영상
      </div>

      <div class="date-button-list">
        ${item.clips.map(clip => `
          <button class="date-btn" onclick="changeVideo('${clip.video}')">
            ${clip.label}
          </button>
        `).join("")}
      </div>
    </div>
  `;

  modal.style.display = "flex";
}

function changeVideo(src) {
  const video = document.querySelector(".main-video");

  if (!video) return;

  video.pause();
  video.src = src;
  video.load();
  video.play();
}

function closeModal() {
  const video = document.querySelector(".main-video");

  if (video) {
    video.pause();
    video.src = "";
  }

  modal.style.display = "none";
  modal.innerHTML = "";
}

modal.onclick = closeModal;

